create table if not exists public.books (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 title text not null, author text not null,
 total_pages integer not null check(total_pages > 0),
 pages_read integer not null default 0 check(pages_read >= 0 and pages_read <= total_pages),
 status text not null default 'planned' check(status in ('planned','reading','read')),
 is_favorite boolean not null default false, notes text not null default '',
 cover_id bigint, open_library_key text,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
-- Dodatna polja za preporuke zasnovane na žanrovima/temama iz Open Libraryja.
alter table public.books add column if not exists subjects text[] not null default '{}';
alter table public.books enable row level security;
create policy "read own books" on public.books for select to authenticated using(auth.uid()=user_id);
create policy "insert own books" on public.books for insert to authenticated with check(auth.uid()=user_id);
create policy "update own books" on public.books for update to authenticated using(auth.uid()=user_id) with check(auth.uid()=user_id);
create policy "delete own books" on public.books for delete to authenticated using(auth.uid()=user_id);
create index if not exists books_user_id_idx on public.books(user_id);